import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { SkillsError } from './errors.mjs'
import { KEY_POINTS_END, keyPointsStart } from './markers.mjs'
import { SKILLS_DIR, plan } from './plan.mjs'

export const GENERATED_NOTICE = '<!-- Generated by scripts/skills/generate.mjs from scripts/skills/config.json and the docs. Do not edit. -->'

function frontmatter({ name, description }) {
  // JSON strings are valid YAML double-quoted scalars: a colon or a quote in the text cannot break the frontmatter
  return `---\nname: ${name}\ndescription: ${JSON.stringify(description)}\n---\n`
}

function renderPage(page) {
  const lines = [`### ${page.title}`, '', `Read when ${page.when}: ${page.url}`]
  if (page.chapters.length) {
    lines.push('', 'Chapters:')
    for (const chapter of page.chapters)
      lines.push(`- [${chapter.heading}](${chapter.url}): ${chapter.when}`)
  }
  lines.push(
    '',
    'Key points, quoted from the page (in French):',
    '',
    keyPointsStart(page.page),
    ...page.keyPoints.map(point => `- ${point}`),
    KEY_POINTS_END,
  )
  return lines.join('\n')
}

function renderDomainSkill(skill) {
  return [
    frontmatter(skill),
    `# ${skill.title}`,
    '',
    GENERATED_NOTICE,
    '',
    'Fetch the page behind a link below before applying a rule that is not covered by its key points: the page is the reference, this skill only routes to it.',
    '',
    '## Reference pages',
    '',
    skill.pages.map(renderPage).join('\n\n'),
    '',
  ].join('\n')
}

function renderEntrySkill(entry, skills) {
  return [
    frontmatter(entry),
    `# ${entry.title}`,
    '',
    GENERATED_NOTICE,
    '',
    'Pick the skill that matches the task, load it, and follow its links to the reference pages.',
    '',
    '## Skills',
    '',
    ...skills.map(skill => `- \`${skill.name}\`: ${skill.summary}`),
    '',
  ].join('\n')
}

/** The generated skills as a map `path relative to the root -> file content`. */
export function renderSkills(root) {
  const { config, skills, problems } = plan(root)
  if (problems.length)
    throw new SkillsError(`Cannot generate the skills:\n${problems.map(p => `- ${p}`).join('\n')}`)
  const files = new Map()
  for (const skill of skills)
    files.set(`${SKILLS_DIR}/${skill.name}/SKILL.md`, renderDomainSkill(skill))
  files.set(`${SKILLS_DIR}/${config.entry.name}/SKILL.md`, renderEntrySkill(config.entry, skills))
  return files
}

export function writeSkills(root) {
  for (const [file, content] of renderSkills(root)) {
    mkdirSync(dirname(join(root, file)), { recursive: true })
    writeFileSync(join(root, file), content)
  }
}
